import assert from 'node:assert/strict';
import {exclusion,importSnapshot,importDelta,ensureLibraryOrder,normalizeVideo,compareAdded,recommend} from '../cloudflare/public/core.mjs';
const id=n=>String(n).padStart(11,'0');
const row=(n,title='How to learn Python')=>({id:id(n),title,position:n,channel:'Example',duration:600});
for(const title of ['TYT Matematik soru çözümü','AYT Fizik konu anlatımı','2026 YKS kampı','KPSS Türkçe ders 12','tyt2026'.replace('2026',' 2026'),'Kamu Personeli Seçme Sınavı soruları'])assert.match(exclusion(row(2000,title)),/Sınav|soru/);
assert.match(exclusion({...row(2000,'Problemler soru çözümü'),channel:'TYT Matematik'}),/Sınav|soru/);
assert.match(exclusion({...row(2000),tags:['KPSS']}),/Sınav|soru/);
for(const title of ['Python ders 1','How to learn physics','Matematik tarihi','Why the sky is blue'])assert.equal(exclusion(row(2000,title)),'');
const full={format:'siradaki-export-v1',complete:true,order:'oldest',videos:Array.from({length:1300},(_,i)=>row(i+1))};
let library=importSnapshot(full);
const newest=vs=>[...vs].sort((a,b)=>compareAdded(b,a)).map(v=>v.id);
assert.deepEqual(newest(library).slice(0,3),[id(1300),id(1299),id(1298)]);
library[1299].notes='keep';library[1299].progress=52;library[1299].progressSource='manual';
const delta=(base,nums)=>({format:'siradaki-delta-v1',complete:true,scope:'new-only',order:'newest',stopReason:'known-page',baseIds:base.map(v=>v.id),matchedIds:[base[0].id],total:base.length+nums.length,scanned:nums.length+1,videos:nums.map(n=>row(n))});
const first=delta(library,[1303,1302,1301]);
library=importDelta(first,library);
assert.deepEqual(newest(library).slice(0,5),[1303,1302,1301,1300,1299].map(id));
const second=delta(library,[1305,1304]);library=importDelta(second,library);
assert.deepEqual(newest(library).slice(0,6),[1305,1304,1303,1302,1301,1300].map(id));
assert.deepEqual(importDelta(first,library),library);
assert.deepEqual(newest(library.map(normalizeVideo)),newest(library));
assert.equal(library.filter(v=>v.baselineExcluded).length,1274);
const refreshed=importSnapshot({...full,videos:Array.from({length:1305},(_,i)=>row(i+1))},library);
assert.deepEqual(newest(refreshed),newest(library));
assert.equal(refreshed.find(v=>v.id===id(1300)).notes,'keep');
assert.equal(refreshed.find(v=>v.id===id(1300)).progress,52);
assert.equal(refreshed.filter(v=>v.baselineExcluded).length,1274);
const legacy=library.map(({libraryOrder,...v})=>v);
const migrated=ensureLibraryOrder(legacy);assert.deepEqual(ensureLibraryOrder(migrated),migrated);assert(newest(migrated).indexOf(id(1301))<newest(migrated).indexOf(id(1300)));
const candidates=[normalizeVideo(row(2000,'TYT soru çözümü')),normalizeVideo(row(2001))];
assert.deepEqual(recommend(candidates,{count:3}).map(v=>v.id),[id(2001)]);
console.log('PASS: exam exclusions and general-course negatives; newest initial/full/multiple incremental imports; replay, backup, migration, notes, progress and permanent baseline.');

