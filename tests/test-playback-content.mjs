const document={hidden:false,documentElement:{},querySelector:()=>video,getElementById:()=>({classList:{contains:()=>ad}}),addEventListener(name,fn){docListeners.set(name,fn)}};
const location={pathname:'/watch',href:'https://www.youtube.com/watch?v=00000000001'};
const MockDate=class extends Date{constructor(...args){super(...(args.length?args:[now]))}static now(){return now}};
const sandbox={document,location,window:{addEventListener(){}},browser:{runtime:{async sendMessage(message){if(message.action==='speed-info'){speedRequests.push(structuredClone(message));return speedInfo;}if(message.action==='set-speed'){setSpeedRequests.push(structuredClone(message));video.playbackRate=message.rate;listeners.get('ratechange')?.();return {ok:true,videoId:message.videoId,rate:video.playbackRate};}messages.push(structuredClone(message));return answer;}}},MutationObserver:class{observe(){}},performance:{now:()=>mono},Date:MockDate,URL,Intl,crypto:webcrypto,queueMicrotask};
vm.runInNewContext(fs.readFileSync('firefox-extension/playback.js','utf8'),sandbox);
const flush=async()=>{for(let i=0;i<6;i++)await Promise.resolve();};
const tick=async(dt,advance,type='timeupdate')=>{mono+=dt;now+=dt;video.currentTime+=advance;listeners.get(type)?.();await flush();};
await flush();assert.equal(messages.length,0,'loading at zero must not replace a saved resume point');
assert(speedRequests.length>0,'the extension requests video language/channel metadata');
assert.equal(video.playbackRate,1,'English audio starts at 1× even when YouTube retained another speed');
video.currentTime=1420;await tick(250,0);assert.equal(messages.length,1);assert.equal(messages[0].event.position,1420);assert.equal(messages[0].event.seconds,0);
video.paused=false;await tick(250,0);for(let i=0;i<64;i++)await tick(250,0.25);
assert(messages.length>=2);assert(messages.at(-1).event.seconds>=14);const before=messages.length;
await tick(10,1000,'seeking');await tick(16000,0);assert.equal(messages.length,before+1);assert(messages.at(-1).event.seconds<17,'seeking does not add 1000 seconds');
ad=true;for(let i=0;i<80;i++)await tick(250,0.25);assert.equal(messages.length,before+1,'ads never report');
ad=false;video.paused=true;await tick(10,0,'pause');assert.equal(messages.at(-1).urgent,true);
answer={ok:false,reset:true};await tick(15000,0);const rejectedCount=messages.length;
video.paused=false;for(let i=0;i<100;i++)await tick(250,0.25);assert.equal(messages.length,rejectedCount,'rejected account/config backs off without a per-event flood');
answer={ok:true};await tick(36000,0);assert.equal(messages.at(-1).event.seconds,0,'disabled/wrong-account interval is discarded');

